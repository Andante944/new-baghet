window.BaghetI18n = (function () {
  const KEY = "baghet_lang";
  let lang = localStorage.getItem(KEY) || "ru";

  function t(key) {
    return (window.BAGHET_I18N[lang] && window.BAGHET_I18N[lang][key]) || key;
  }

  function apply() {
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      el.textContent = t(key);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
      el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
    });
    document.querySelectorAll(".lang-btn").forEach((btn) => {
      btn.classList.toggle("is-active", btn.dataset.lang === lang);
      btn.setAttribute("aria-pressed", btn.dataset.lang === lang ? "true" : "false");
    });
  }

  function setLang(next) {
    if (!window.BAGHET_I18N[next]) return;
    lang = next;
    localStorage.setItem(KEY, lang);
    apply();
    document.dispatchEvent(new CustomEvent("baghet:lang", { detail: { lang } }));
  }

  function getLang() {
    return lang;
  }

  return { t, apply, setLang, getLang };
})();
